-- 功能：集中管理共享数据库结构；服务启动时只验证，不自行建表。
-- 初始化在服务启动前执行，避免多个 Hibernate 实例同时执行 DDL。
BEGIN;

-- 功能：商品目录在初始化后只读；价格使用十进制定点数保存。
CREATE TABLE IF NOT EXISTS catalog_items (
    sku varchar(32) PRIMARY KEY,
    name varchar(255) NOT NULL,
    price numeric(10,2) NOT NULL CHECK (price >= 0)
);

-- 功能：库存与商品一一对应；数据库约束是禁止负库存的最后一道保障。
CREATE TABLE IF NOT EXISTS inventory (
    sku varchar(32) PRIMARY KEY REFERENCES catalog_items(sku),
    current_stock integer NOT NULL CHECK (current_stock >= 0),
    low_stock_triggered_at timestamptz
);

-- 功能：记录每次购物的状态和汇总；行锁及 version 共同保护并发更新。
CREATE TABLE IF NOT EXISTS checkout_transactions (
    transaction_id varchar(36) PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    station_id varchar(255) NOT NULL,
    status varchar(255) NOT NULL CHECK (status IN ('OPEN','COMPLETED','CANCELLED')),
    item_count integer NOT NULL CHECK (item_count >= 0),
    running_total numeric(10,2) NOT NULL CHECK (running_total >= 0),
    started_at timestamptz NOT NULL,
    completed_at timestamptz
);

-- 功能：保存扫描时的商品名称和价格快照；相同交易内每个 SKU 仅一行。
CREATE TABLE IF NOT EXISTS transaction_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id varchar(36) NOT NULL REFERENCES checkout_transactions(transaction_id),
    sku varchar(32) NOT NULL REFERENCES catalog_items(sku),
    item_name varchar(255) NOT NULL,
    unit_price numeric(10,2) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    CONSTRAINT unique_transaction_sku UNIQUE (transaction_id, sku)
);

-- 功能：Checkout 与购物篮一起提交原始事件；IDENTITY 仅用于唯一标识，允许回滚空洞。
CREATE TABLE IF NOT EXISTS scan_outbox (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(32) NOT NULL REFERENCES catalog_items(sku),
    processed boolean NOT NULL DEFAULT false
);
-- 功能：Analytics 只查未处理前缀，避免每批反复扫描已经处理的大量历史数据。
CREATE INDEX IF NOT EXISTS scan_outbox_pending ON scan_outbox(event_id) WHERE processed = false;

-- 功能：Analytics 整理已提交 outbox 后生成连续分析序号；来源唯一保证每个事件只处理一次。
CREATE TABLE IF NOT EXISTS scan_events (
    sequence bigint PRIMARY KEY CHECK (sequence > 0),
    sku varchar(32) NOT NULL REFERENCES catalog_items(sku),
    source_event_id bigint UNIQUE REFERENCES scan_outbox(event_id)
);

-- 功能：保留已有分析历史；旧记录允许没有 outbox 来源，新记录由 Analytics 带来源写入。
ALTER TABLE scan_events ADD COLUMN IF NOT EXISTS source_event_id bigint UNIQUE REFERENCES scan_outbox(event_id);
-- 功能：删除旧版逐扫描取全局锁的函数；新客户端写入只经过 outbox。
DROP FUNCTION IF EXISTS append_checkout_scan(varchar);

-- 功能：保存窗口检查点；唯一终点支持失败重试及重启恢复。
CREATE TABLE IF NOT EXISTS analytics_windows (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_size integer NOT NULL,
    slide_interval integer NOT NULL,
    window_start bigint NOT NULL,
    window_end bigint NOT NULL UNIQUE,
    computed_at timestamptz NOT NULL
);

-- 功能：与窗口一起原子保存前十名；唯一约束阻止同一窗口重复名次/SKU。
CREATE TABLE IF NOT EXISTS popular_item_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_id bigint NOT NULL REFERENCES analytics_windows(id),
    sku varchar(32) NOT NULL REFERENCES catalog_items(sku),
    name varchar(255) NOT NULL,
    scan_count integer NOT NULL CHECK (scan_count > 0),
    rank integer NOT NULL CHECK (rank > 0),
    UNIQUE (window_id, rank),
    UNIQUE (window_id, sku)
);
COMMIT;
