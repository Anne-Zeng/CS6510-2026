-- 功能：仅在 analytics_db 执行；无跨服务外键。
BEGIN;
CREATE TABLE IF NOT EXISTS scan_inbox (
 received_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key varchar(36) NOT NULL UNIQUE,
 sku varchar(32) NOT NULL,
 name varchar(255) NOT NULL,
 processed boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS scan_inbox_pending ON scan_inbox(received_id) WHERE processed=false;
CREATE TABLE IF NOT EXISTS scan_events (
 sequence bigint PRIMARY KEY CHECK(sequence>0),
 event_key varchar(36) NOT NULL UNIQUE REFERENCES scan_inbox(event_key),
 sku varchar(32) NOT NULL,
 name varchar(255) NOT NULL
);
CREATE INDEX IF NOT EXISTS scan_events_sku_sequence ON scan_events(sku,sequence DESC);
CREATE TABLE IF NOT EXISTS analytics_windows (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_size integer NOT NULL,
    slide_interval integer NOT NULL,
    window_start bigint NOT NULL,
    window_end bigint NOT NULL UNIQUE,
    computed_at timestamptz NOT NULL
);

-- 功能：与窗口一起原子保存前十名；唯一约束阻止同一窗口重复名次/SKU。
CREATE TABLE IF NOT EXISTS popular_item_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_id bigint NOT NULL REFERENCES analytics_windows(id),
    sku varchar(32) NOT NULL,
    name varchar(255) NOT NULL,
    scan_count integer NOT NULL CHECK (scan_count > 0),
    rank integer NOT NULL CHECK (rank > 0),
    UNIQUE (window_id, rank),
    UNIQUE (window_id, sku)
);

COMMIT;

-- 升级时先整理旧版本已接收但未编号的事件；保留原表与全部数据。
BEGIN;
SELECT pg_advisory_xact_lock(6510,3);
WITH pending AS MATERIALIZED (
 SELECT received_id,event_key,sku,name FROM scan_inbox WHERE processed=false ORDER BY received_id FOR UPDATE
), inserted AS (
 INSERT INTO scan_events(sequence,event_key,sku,name)
 SELECT base.last_sequence+row_number() OVER(ORDER BY p.received_id),p.event_key,p.sku,p.name
 FROM pending p CROSS JOIN (SELECT COALESCE(MAX(sequence),0) AS last_sequence FROM scan_events) base
 RETURNING event_key
)
UPDATE scan_inbox inbox SET processed=true FROM inserted i WHERE inbox.event_key=i.event_key;
COMMIT;
