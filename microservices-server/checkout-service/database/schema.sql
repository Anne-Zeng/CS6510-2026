-- 功能：只在 checkout_db 执行，无跨服务外键。扫描与 outbox 在同一个本地事务提交。
BEGIN;
CREATE TABLE IF NOT EXISTS checkout_transactions (
    transaction_id varchar(36) PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    station_id varchar(255) NOT NULL,
    status varchar(255) NOT NULL CHECK (status IN ('OPEN','CHECKOUT_PENDING','COMPLETED','CANCELLED')),
    item_count integer NOT NULL CHECK (item_count >= 0),
    running_total numeric(10,2) NOT NULL CHECK (running_total >= 0),
    started_at timestamptz NOT NULL,
    completed_at timestamptz
);

-- 功能：保存扫描时的商品名称和价格快照；相同交易内每个 SKU 仅一行。
CREATE TABLE IF NOT EXISTS transaction_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id varchar(36) NOT NULL REFERENCES checkout_transactions(transaction_id),
    sku varchar(32) NOT NULL,
    item_name varchar(255) NOT NULL,
    unit_price numeric(10,2) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    CONSTRAINT unique_transaction_sku UNIQUE (transaction_id, sku)
);

-- 功能：Checkout 与购物篮一起提交原始事件；IDENTITY 仅用于唯一标识，允许回滚空洞。
CREATE TABLE IF NOT EXISTS scan_outbox (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(32) NOT NULL,
    processed boolean NOT NULL DEFAULT false
);

COMMIT;

-- 功能：保留已有购物篮与 outbox，增加冻结状态和持久化 Saga 记录。
BEGIN;
ALTER TABLE checkout_transactions DROP CONSTRAINT IF EXISTS checkout_transactions_status_check;
ALTER TABLE checkout_transactions ADD CONSTRAINT checkout_transactions_status_check
 CHECK (status IN ('OPEN','CHECKOUT_PENDING','COMPLETED','CANCELLED'));
CREATE TABLE IF NOT EXISTS checkout_sagas (
 saga_id varchar(36) PRIMARY KEY,
 transaction_id varchar(36) NOT NULL REFERENCES checkout_transactions(transaction_id),
 state varchar(16) NOT NULL CHECK(state IN ('RESERVING','COMMITTING','CANCELLING','DONE','ABORTED')),
 attempts integer NOT NULL DEFAULT 0,
 last_error varchar(1000),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 next_attempt_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS checkout_one_active_saga ON checkout_sagas(transaction_id)
 WHERE state IN ('RESERVING','COMMITTING','CANCELLING');
CREATE INDEX IF NOT EXISTS checkout_saga_recovery ON checkout_sagas(next_attempt_at)
 WHERE state IN ('RESERVING','COMMITTING','CANCELLING');
COMMIT;

-- 功能：保留已扫描事件；为 HTTP 重试增加稳定 UUID 与名称快照。
BEGIN;
ALTER TABLE scan_outbox ADD COLUMN IF NOT EXISTS event_key varchar(36) NOT NULL DEFAULT gen_random_uuid()::text;
ALTER TABLE scan_outbox ADD COLUMN IF NOT EXISTS item_name varchar(255);
UPDATE scan_outbox o SET item_name=names.item_name
FROM (SELECT DISTINCT ON (sku) sku,item_name FROM transaction_items ORDER BY sku,id DESC) names
WHERE o.sku=names.sku AND o.item_name IS NULL;
-- 功能：存在无法还原名称的旧事件时明确失败，不跳过或删除事件。
ALTER TABLE scan_outbox ALTER COLUMN item_name SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS scan_outbox_event_key ON scan_outbox(event_key);
CREATE INDEX IF NOT EXISTS scan_outbox_pending ON scan_outbox(event_id) WHERE processed=false;
COMMIT;

-- 功能：为同一 Saga 的前台与后台推进增加持久租约；保留所有已有记录。
BEGIN;
ALTER TABLE checkout_sagas ADD COLUMN IF NOT EXISTS lease_owner varchar(36);
ALTER TABLE checkout_sagas ADD COLUMN IF NOT EXISTS lease_until timestamptz;
COMMIT;
